    // "All" toggle in the Add-Users header.
    // Originally this only flipped .proj_mem_chk (the admin checkbox group
    // rendered at the top of the form), which surprised every user who
    // saw a checkbox literally labelled "All" and expected ALL the users
    // below to also get selected. Now toggles both:
    //   - .proj_mem_chk          → owner + admins shown above
    //   - .add_user_chk_Prj      → all non-admin users in the lower grid
    // The function name is kept so any external caller still works.
    function checkUncheckAdmnUsers() {
        var on = $('#alladmn_users').is(':checked');
        $('.proj_mem_chk').prop('checked', on);
        $('.add_user_chk_Prj').prop('checked', on);
    }

    // Keep the "All" checkbox in sync with the actual state of the two
    // user-checkbox groups. The header "All" should be:
    //   - CHECKED only when EVERY visible user checkbox is checked
    //   - UNCHECKED otherwise
    // Without this the header could be hardcoded checked while individual
    // user checkboxes below are not — a misleading state we hit before.
    function _syncAllCheckboxState() {
        var $all = $('#alladmn_users');
        if (!$all.length) return;
        var $boxes = $('.proj_mem_chk, .add_user_chk_Prj');
        if (!$boxes.length) {
            // No user checkboxes to mirror — leave "All" alone.
            return;
        }
        var allChecked = $boxes.length === $boxes.filter(':checked').length;
        $all.prop('checked', allChecked);
    }

    // Wire per-checkbox change listeners so unchecking any single user
    // auto-unchecks "All", and ticking the last remaining user
    // auto-checks "All". Bound on jQuery .on(change) at the document
    // level so it also catches checkboxes rendered after this script
    // first runs (e.g. when the form opens via AJAX).
    $(document).on('change', '.proj_mem_chk, .add_user_chk_Prj', function () {
        _syncAllCheckboxState();
    });

    // Initial sync — runs once the modal is in the DOM. Use a setTimeout
    // 0 so the call queues after the rest of the page-load DOM updates.
    setTimeout(_syncAllCheckboxState, 0);
